/**
 * Normaliza um nome de cidade para o padrão oficial:
 * - Primeira letra de cada palavra em maiúsculo (exceto preposições)
 * - Acentos corretos conforme grafia oficial do IBGE
 * - Trim + colapso de espaços múltiplos
 *
 * @param cidade - valor bruto digitado pelo usuário
 * @returns nome normalizado, ou string vazia se entrada vazia
 */
export function normalizeCidadeInput(cidade: string | null | undefined): string {
  if (!cidade) return "";
  const trimmed = cidade.trim().replace(/\s+/g, " ");
  if (!trimmed) return "";

  const key = toKey(trimmed);
  if (MUNICIPIOS[key]) return MUNICIPIOS[key];

  // Não encontrado na tabela → aplica Title Case português
  return titleCasePT(trimmed);
}
