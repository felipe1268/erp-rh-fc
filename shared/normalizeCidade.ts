/**
 * Normalização de nomes de cidades brasileiras.
 *
 * Regras:
 *   1. Trim + colapsar espaços múltiplos
 *   2. Buscar na tabela de municípios (chave = sem acento, sem caixa)
 *   3. Se não encontrar, aplicar Title Case português (artigos/preposições minúsculos)
 *
 * Usado no backend (createEmployee / updateEmployee) e no frontend (onBlur do campo Cidade).
 */

// ─── helpers ────────────────────────────────────────────────────────────────

/** Remove acentos e converte para minúsculas — chave de busca */
export function toKey(s: string): string {
  return s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
    .replace(/\s+/g, " ");
}

const LOWER_WORDS = new Set(["de", "da", "do", "das", "dos", "e", "em"]);

/** Title Case português: preposições/artigos minúsculos exceto 1ª palavra */
function titleCasePT(s: string): string {
  return s
    .toLowerCase()
    .split(" ")
    .map((w, i) => {
      if (w === "") return w;
      if (i > 0 && LOWER_WORDS.has(w)) return w;
      return w.charAt(0).toUpperCase() + w.slice(1);
    })
    .join(" ");
}

